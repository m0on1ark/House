CREATE TABLE deal_messages
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    deal_id    BIGINT                                  NOT NULL,
    author_id  BIGINT                                  NOT NULL,
    text       VARCHAR(1000)                           NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_deal_messages PRIMARY KEY (id),
    CONSTRAINT fk_deal_messages_on_deal FOREIGN KEY (deal_id) REFERENCES deals (id),
    CONSTRAINT fk_deal_messages_on_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE TABLE building_messages
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    building_id BIGINT                                  NOT NULL,
    author_id   BIGINT                                  NOT NULL,
    text        VARCHAR(1000)                           NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_building_messages PRIMARY KEY (id),
    CONSTRAINT fk_building_messages_on_building FOREIGN KEY (building_id) REFERENCES buildings (id),
    CONSTRAINT fk_building_messages_on_author FOREIGN KEY (author_id) REFERENCES users (id)
);
