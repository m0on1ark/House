CREATE TABLE deals
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    building_id    BIGINT                                  NOT NULL,
    author_id      BIGINT                                  NOT NULL,
    product_name   VARCHAR(255)                            NOT NULL,
    store_name     VARCHAR(255)                            NOT NULL,
    total_units    INT                                     NOT NULL,
    author_units   INT                                     NOT NULL,
    price_per_unit DOUBLE PRECISION,
    status         VARCHAR(255)                            NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_deals PRIMARY KEY (id),
    CONSTRAINT fk_deals_on_building FOREIGN KEY (building_id) REFERENCES buildings (id),
    CONSTRAINT fk_deals_on_author FOREIGN KEY (author_id) REFERENCES users (id)
);

CREATE TABLE deal_claims
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    deal_id BIGINT                                  NOT NULL,
    user_id BIGINT                                  NOT NULL,
    units   INT                                     NOT NULL,
    CONSTRAINT pk_deal_claims PRIMARY KEY (id),
    CONSTRAINT uq_deal_claims_deal_user UNIQUE (deal_id, user_id),
    CONSTRAINT fk_deal_claims_on_deal FOREIGN KEY (deal_id) REFERENCES deals (id),
    CONSTRAINT fk_deal_claims_on_user FOREIGN KEY (user_id) REFERENCES users (id)
);
